def main():
    conn = psycopg2.connect(DATABASE_URL)
    cur = conn.cursor()

    cur.execute("SET search_path = acme, public")

    # 1. Companies
    print("Inserting companies...")
    for c in COMPANIES:
        cur.execute("""
            INSERT INTO core_companies (
                id, name, legal_name, gstin, pan, cin,
                default_currency_id, fiscal_year_start_month,
                address_line1, address_line2, city, state, pincode, country,
                is_active, industry, founded_date,
                is_consolidation_only, gsp_provider,
                created_at, updated_at
            ) VALUES (
                %s, %s, %s, %s, %s, %s,
                %s, %s,
                %s, %s, %s, %s, %s, %s,
                true, %s, %s,
                false, 'mock',
                now(), now()
            )
            ON CONFLICT (id) DO NOTHING
        """, (
            c["id"], c["name"], c["legal_name"], c["gstin"], c["pan"], c["cin"],
            DEFAULT_CURRENCY_ID, c["fiscal_year_start_month"],
            c["address_line1"], c["address_line2"], c["city"], c["state"],
            c["pincode"], c["country"],
            c["industry"], c["founded_date"],
        ))
    print(f"  {len(COMPANIES)} companies processed")

    # 2. Permissions
    print("Inserting permissions...")
    for perm in PERMISSIONS:
        cur.execute("""
            INSERT INTO core_permissions (id, code, module, resource, action)
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT (id) DO NOTHING
        """, perm)
    print(f"  {len(PERMISSIONS)} permissions processed")

    # 3. Roles
    print("Inserting roles...")
    for role in ROLES:
        cur.execute("""
            INSERT INTO core_roles (id, company_id, name, description, is_system)
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT (id) DO NOTHING
        """, role)
    print(f"  {len(ROLES)} roles processed")

    # 4. Role → Permission mappings
    print("Inserting role_permissions...")
    for rp in ROLE_PERMISSIONS:
        cur.execute("""
            INSERT INTO core_role_permissions (role_id, permission_id)
            VALUES (%s, %s)
            ON CONFLICT DO NOTHING
        """, rp)
    print(f"  {len(ROLE_PERMISSIONS)} role_permissions processed")

    conn.commit()
    cur.close()
    conn.close()

    print()
    print("=" * 60)
    print("Done. Two companies created in acme schema:")
    print("  1. Impacgo solutions Private Limited  (20 ERP roles)")
    print("  2. impacgo people                     (11 HCM roles)")
    print("  Permissions: 128 entries seeded")
    print("=" * 60)


if __name__ == "__main__":
    main()
