_NUMERIC_RE = re.compile(r"^[-+]?(₹|\$|rs\.?\s*)?[\d,]+(\.\d+)?\s*(%|h|hrs?|hours?|d|days?|day\(s\))?$", re.I)

_FONT_PATH = Path(__file__).parent / "report_assets" / "Inter.ttf"


@lru_cache(maxsize=1)
def _font_face_css() -> str:
    try:
        data = base64.b64encode(_FONT_PATH.read_bytes()).decode("ascii")
    except OSError:
        return ""
    return (
        "@font-face{font-family:'Inter';font-weight:100 900;font-style:normal;"
        f"src:url(data:font/ttf;base64,{data}) format('truetype');}}"
    )


def _e(value) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def _is_numeric(cell: str) -> bool:
    c = cell.strip()
    return bool(c) and c not in ("—", "-") and bool(_NUMERIC_RE.match(c))


def _numeric_columns(columns: list[str], rows: list[list[str]]) -> set[int]:
    """A column is right-aligned when (almost) every filled cell is a
    number, amount, percentage or duration."""
    out: set[int] = set()
    sample = rows[:400]
    for i in range(len(columns)):
        cells = [r[i].strip() for r in sample if i < len(r) and r[i].strip() not in ("", "—", "-")]
        if cells and sum(_is_numeric(c) for c in cells) >= 0.9 * len(cells):
            out.add(i)
    return out


def _status_columns(columns: list[str]) -> set[int]:
    return {i for i, c in enumerate(columns) if "status" in c.lower()}


def _pill(text: str) -> str:
    fg, bg = _STATUS_COLORS.get(text.strip().lower().replace("_", " "), (_TEXT_SOFT, "#EEF0F5"))
    return f'<span class="pill" style="color:{fg};background:{bg}">{_e(text)}</span>'


def _point_color(label: str, i: int) -> str:
    """A chart slice/segment named after a status keeps that status's
    color (Approved green, Pending amber, Rejected red ...); anything else
    takes the next color in the brand cycle."""
    status = _STATUS_COLORS.get(label.strip().lower().replace("_", " "))
    return status[0] if status else _SERIES[i % len(_SERIES)]


def _fmt_number(v: float) -> str:
    if abs(v - round(v)) < 1e-9:
        return f"{int(round(v)):,}"
    return f"{v:,.1f}"


def _company_info(company) -> dict:
    logo = resolve_company_logo(company) if company is not None else TRANSPARENT_PIXEL_DATA_URL
    name = getattr(company, "name", None) or "Company"
    address = ", ".join(
        p for p in (
            getattr(company, "address_line1", None), getattr(company, "address_line2", None),
            getattr(company, "city", None), getattr(company, "state", None),
            getattr(company, "pincode", None),
        ) if p
    )
    legal = getattr(company, "legal_name", None)
    return {
        "name": name,
        "logo": None if logo == TRANSPARENT_PIXEL_DATA_URL else logo,
        "legal": legal if legal and legal.strip() != name.strip() else None,
        "address": address or None,
        "gstin": getattr(company, "gstin", None),
    }


def _letterhead(info: dict, title: str, period: str | None, generated_at: str, generated_by: str | None) -> str:
    if info["logo"]:
        mark = f'<img class="logo" src="{_e(info["logo"])}" alt="">'
    else:
        initials = "".join(w[0] for w in info["name"].split()[:2]).upper() or "C"
        mark = f'<div class="monogram">{_e(initials)}</div>'
    sub = []
    if info["legal"]:
        sub.append(_e(info["legal"]))
    if info["address"]:
        sub.append(_e(info["address"]))
    if info["gstin"]:
        sub.append(f"GSTIN: {_e(info['gstin'])}")
    meta = [("Report", title)]
    if period:
        meta.append(("Period", period))
    meta.append(("Generated on", generated_at))
    if generated_by:
        meta.append(("Generated by", generated_by))
    meta_rows = "".join(f"<tr><th>{_e(k)}</th><td>{_e(v)}</td></tr>" for k, v in meta)
    return (
        '<header class="letterhead">'
        f'<div class="lh-brand">{mark}<div><div class="company">{_e(info["name"])}</div>'
        f'<div class="company-sub">{"<br>".join(sub)}</div></div></div>'
        f'<table class="lh-meta">{meta_rows}</table></header>'
        '<div class="rule"><span></span></div>'
    )


def _watermark(info: dict) -> str:
    """Fixed-position, so headless Chromium repeats it on every printed
    page; drawn above the content at a very low opacity (like a real
    watermark) so table/card backgrounds never hide it."""
    if info["logo"]:
        return f'<div class="watermark"><img src="{_e(info["logo"])}" alt=""></div>'
    size = max(26, min(68, int(1000 / max(len(info["name"]), 1))))
    return f'<div class="watermark text"><span style="font-size:{size}pt">{_e(info["name"])}</span></div>'


def _kpis(summary: list[dict]) -> str:
    if not summary:
        return ""
    tiles = []
    for i, item in enumerate(summary):
        color = _SERIES[i % len(_SERIES)]
        tiles.append(
            f'<div class="kpi" style="border-left-color:{color}">'
            f'<div class="kpi-label">{_e(item.get("label"))}</div>'
            f'<div class="kpi-value">{_e(item.get("value"))}</div></div>'
        )
    return f'<div class="kpis">{"".join(tiles)}</div>'


def _donut_svg(points: list[tuple[str, float]]) -> str:
    total = sum(v for _, v in points) or 1.0
    r, c = 52.0, 2 * math.pi * 52.0
    offset = 0.0
    arcs = []
    for i, (_, v) in enumerate(points):
        length = c * (v / total)
        arcs.append(
            f'<circle r="{r}" cx="70" cy="70" fill="none" stroke="{_point_color(points[i][0], i)}" '
            f'stroke-width="22" stroke-dasharray="{length:.2f} {c - length:.2f}" '
            f'stroke-dashoffset="{-offset:.2f}" transform="rotate(-90 70 70)"/>'
        )
        offset += length
    legend = "".join(
        f'<div class="legend-row"><span class="dot" style="background:{_point_color(label, i)}"></span>'
        f'<span class="legend-label">{_e(label)}</span>'
        f'<span class="legend-value">{_fmt_number(v)} <em>({v / total * 100:.0f}%)</em></span></div>'
        for i, (label, v) in enumerate(points)
    )
    return (
        '<div class="donut"><svg width="140" height="140" viewBox="0 0 140 140">'
        f'<circle r="{r}" cx="70" cy="70" fill="none" stroke="#EEF0F5" stroke-width="22"/>{"".join(arcs)}'
        f'<text x="70" y="68" text-anchor="middle" class="donut-total">{_fmt_number(total)}</text>'
        '<text x="70" y="84" text-anchor="middle" class="donut-caption">TOTAL</text></svg>'
        f'<div class="legend">{legend}</div></div>'
    )


def _hbars(points: list[tuple[str, float]], color: str) -> str:
    peak = max((v for _, v in points), default=0) or 1.0
    rows = "".join(
        f'<div class="bar-row"><div class="bar-label">{_e(label)}</div>'
        f'<div class="bar-track"><div class="bar-fill" style="width:{max(v / peak * 100, 0.8):.1f}%;background:{color}"></div></div>'
        f'<div class="bar-value">{_fmt_number(v)}</div></div>'
        for label, v in points
    )
    return f'<div class="bars">{rows}</div>'


_MONTH_YEAR_RE = re.compile(r"^([A-Za-z]{3})[a-z]*\s+(\d{4})$")


_DAY_MONTH_RE = re.compile(r"^(\d{1,2})\s+([A-Za-z]{3})[a-z]*$")


def _short_axis_labels(labels: list[str]) -> list[str]:
    days = [_DAY_MONTH_RE.match(lbl.strip()) for lbl in labels]
    if labels and all(days) and len({m.group(2) for m in days}) == 1:
        return [m.group(1) for m in days]
    matches = [_MONTH_YEAR_RE.match(lbl.strip()) for lbl in labels]
    if not labels or not all(matches):
        return labels
    years = {m.group(2) for m in matches}
    if len(years) == 1:
        return [m.group(1) for m in matches]
    return [f"{m.group(1)} '{m.group(2)[2:]}" for m in matches]


def _columns_chart(points: list[tuple[str, float]], color: str) -> str:
    peak = max((v for _, v in points), default=0) or 1.0
    points = list(zip(_short_axis_labels([lbl for lbl, _ in points]), [v for _, v in points]))
    cols = "".join(
        f'<div class="col"><div class="col-value">{_fmt_number(v)}</div>'
        f'<div class="col-bar" style="height:{max(v / peak * 68, 1.5):.1f}%;background:{color}"></div>'
        f'<div class="col-label">{_e(label)}</div></div>'
        for label, v in points
    )
    return f'<div class="columns">{cols}</div>'


def _stacked(series: list[dict]) -> str:
    labels: list[str] = []
    for s in series:
        for p in s.get("points", []):
            if p["label"] not in labels:
                labels.append(p["label"])
    values = {
        (s["name"], p["label"]): float(p["value"]) for s in series for p in s.get("points", [])
    }
    totals = {lbl: sum(values.get((s["name"], lbl), 0.0) for s in series) for lbl in labels}
    peak = max(totals.values(), default=0) or 1.0
    rows = []
    for lbl in labels[:15]:
        segs = "".join(
            f'<div style="width:{values.get((s["name"], lbl), 0.0) / peak * 100:.2f}%;background:{_point_color(s["name"], i)}"></div>'
            for i, s in enumerate(series)
        )
        rows.append(
            f'<div class="bar-row"><div class="bar-label">{_e(lbl)}</div>'
            f'<div class="bar-track stacked">{segs}</div><div class="bar-value">{_fmt_number(totals[lbl])}</div></div>'
        )
    legend = "".join(
        f'<span class="legend-inline"><span class="dot" style="background:{_point_color(s["name"], i)}"></span>{_e(s["name"])}</span>'
        for i, s in enumerate(series)
    )
    return f'<div class="bars">{"".join(rows)}</div><div class="legend-inline-wrap">{legend}</div>'


def _chart(chart: dict) -> str:
    series = [s for s in chart.get("series", []) if s.get("points")]
    if not series:
        return ""
    kind = chart.get("chart_type", "bar")
    first = [(p["label"], float(p["value"])) for p in series[0]["points"]]
    if kind == "stacked_bar" or len(series) > 1:
        body = _stacked(series)
    elif kind == "donut":
        pts = sorted(first, key=lambda x: x[1], reverse=True)
        if len(pts) > 8:
            pts = pts[:7] + [("Others", sum(v for _, v in pts[7:]))]
        pts = [p for p in pts if p[1] > 0]
        if not pts:
            return ""
        body = _donut_svg(pts)
    elif kind == "line":
        body = _columns_chart(first[-14:], _BLUE)
    else:
        body = _hbars(first[:15], _BLUE)
    return f'<div class="chart"><div class="chart-title">{_e(chart.get("title"))}</div>{body}</div>'


def _table(columns: list[str], rows: list[list[str]]) -> str:
    if not columns:
        return ""
    numeric = _numeric_columns(columns, rows)
    status = _status_columns(columns)
    dates = {i for i, c in enumerate(columns) if re.search(r"\b(date|day|month|period)\b", c.lower())}
    head = '<th class="idx">#</th>' + "".join(
        f'<th class="{"num" if i in numeric else ""}">{_e(c)}</th>' for i, c in enumerate(columns)
    )
    if not rows:
        body = f'<tr><td class="empty" colspan="{len(columns) + 1}">No records for the selected filters.</td></tr>'
    else:
        out = []
        for n, r in enumerate(rows, start=1):
            cells = [f'<td class="idx">{n}</td>']
            for i in range(len(columns)):
                v = r[i] if i < len(r) else ""
                if i in status and v.strip() and v.strip() != "—":
                    cells.append(f"<td>{_pill(v)}</td>")
                elif i in numeric:
                    cells.append(f'<td class="num">{_e(v)}</td>')
                elif i == 0:
                    cells.append(f'<td class="first">{_e(v)}</td>')
                elif i in dates:
                    cells.append(f'<td class="nowrap">{_e(v)}</td>')
                else:
                    cells.append(f"<td>{_e(v)}</td>")
            out.append(f"<tr>{''.join(cells)}</tr>")
        body = "".join(out)
    return f'<table class="data"><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>'


