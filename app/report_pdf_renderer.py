def render_report_pdf(payload: dict, company, generated_by: str | None) -> bytes:
    columns: list[str] = payload.get("columns") or []
    rows: list[list[str]] = payload.get("rows") or []
    summary = payload.get("summary") or []
    landscape = len(columns) > 7
    info = _company_info(company)
    title = payload.get("title") or "Report"
    generated_at = payload.get("generated_at") or datetime.datetime.now().strftime("%d %b %Y, %I:%M %p")
    period = payload.get("period_label")
    subtitle = payload.get("subtitle")

    filters = "".join(
        f'<span class="chip">{_e(f.get("label"))}: <b>{_e(f.get("value"))}</b></span>'
        for f in payload.get("filters") or [] if f.get("value")
    )
    charts = "".join(_chart(c) for c in payload.get("charts") or [])
    record_word = "record" if len(rows) == 1 else "records"

    # Order: the data first, then its summary and insights, then the close.
    sections = []
    n = 0

    def section(name: str) -> str:
        nonlocal n
        n += 1
        return f'<div class="section"><h2><span class="num">{n:02d}</span>{_e(name)}</h2><span class="line"></span></div>'

    sections.append(f'{section("Detailed Records")}<div class="block">{_table(columns, rows)}</div>')
    if summary:
        sections.append(f'<div class="block keep">{section("Summary")}{_kpis(summary)}</div>')
    if charts:
        sections.append(f'{section("Insights")}<div class="block charts">{charts}</div>')

    by = f" by {_e(generated_by)}" if generated_by else ""
    body = f"""
{_watermark(info)}
{_letterhead(info, title, period, generated_at, generated_by)}
<div class="title-row"><div><h1>{_e(title)}</h1>
  {f'<div class="subtitle">{_e(subtitle)}</div>' if subtitle else ''}</div>
  <div class="count-badge"><b>{len(rows):,}</b>{record_word}</div></div>
{f'<div class="filters">{filters}</div>' if filters else ''}
{''.join(sections)}
<div class="end"><div class="end-mark">End of Report</div>
  <div class="end-note">{len(rows):,} {record_word} · Generated on {_e(generated_at)}{by}<br>
  This is a system-generated report from {_e(info["name"])} and does not require a signature.
  Confidential — for internal use only.</div></div>
"""
    doc = (
        '<!DOCTYPE html><html><head><meta charset="utf-8">'
        f"<title>{_e(title)}</title><style>{_css(landscape, len(summary))}</style></head>"
        f"<body>{body}</body></html>"
    )
    footer = (
        '<div style="width:100%;font-size:7px;color:#8A91A3;padding:0 12mm;display:flex;'
        "justify-content:space-between;align-items:center;font-family:Arial,sans-serif;\">"
        f"<span style=\"flex:1\">{_e(info['name'])} · {_e(title)}</span>"
        '<span style="flex:1;text-align:center;letter-spacing:1px">CONFIDENTIAL</span>'
        '<span style="flex:1;text-align:right">Page <span class="pageNumber"></span> of <span class="totalPages"></span></span></div>'
    )
    return render_html_to_pdf(
        doc,
        {"display_header_footer": True, "header_template": "<div></div>", "footer_template": footer},
    )
